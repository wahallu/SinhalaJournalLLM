#!/usr/bin/env python3
"""Rebuild app/services/grammar/data/journal_verb_forms.json from published news.

journal_rules.py corrects a verb ending only towards a form that published
Sinhala news actually uses. This script derives those forms: it counts every
token and every sentence-final token across the scraped news corpora, then
keeps a masculine/feminine/plural (past) or singular/plural (present) row only
when each form is attested often enough.

    ./.venv/bin/python scripts/build_journal_verb_forms.py
"""

from __future__ import annotations

import argparse
import json
import re
from collections import Counter
from pathlib import Path

SCRIPT = Path(__file__).resolve()
RESEARCH = SCRIPT.parents[4]
OUTPUT = SCRIPT.parents[1] / "app/services/grammar/data/journal_verb_forms.json"
JSON_SOURCES = ("manual dataset/lankadeepa.json", "manual dataset/itn_merged.json")
JSONL_SOURCES = (
    "SinhalaJournal LLM-Dataset and my files/Ada derana/biz_adaderana.jsonl",
    "SinhalaJournal LLM-Dataset and my files/Ada derana/sinhala_adaderana_international.jsonl",
)
MIN_FINAL, MIN_FORM = 20, 5
PUNCT = ".,;:!?\"'“”‘’()[]{}"
SPLIT = re.compile(r"(?<=[.!?])\s+|\n+")

# Irregular plurals cannot be generated from the stem; each is still checked
# against the corpus like every generated form.
IRREGULAR = (
    ("දුන්නේය", "දුන්නාය", "දුන්හ"), ("ගත්තේය", "ගත්තාය", "ගත්හ"), ("ආවේය", "ආවාය", "ආහ"),
    ("කීය", "කීවාය", "කීහ"), ("කීවේය", "කීවාය", "කීහ"), ("විය", None, "වූහ"),
)
COLLOQUIAL_TO_PLURAL = {
    "කළා": "කළහ", "ගියා": "ගියහ", "ආවා": "ආහ", "කිව්වා": "කීහ", "දුන්නා": "දුන්හ", "ගත්තා": "ගත්හ",
    "සිටියා": "සිටියහ", "හිටියා": "සිටියහ", "පැවසුවා": "පැවසූහ", "වුණා": "වූහ", "පැමිණියා": "පැමිණියහ",
    "කරනවා": "කරති", "කියනවා": "කියති", "යනවා": "යති", "ඉන්නවා": "සිටිති", "දෙනවා": "දෙති", "පවසනවා": "පවසති",
}


def _articles(root: Path):
    for name in JSON_SOURCES:
        yield from json.loads((root / name).read_text(encoding="utf-8"))
    for name in JSONL_SOURCES:
        for line in (root / name).open(encoding="utf-8"):
            try:
                yield json.loads(line)
            except json.JSONDecodeError:
                continue


def count(root: Path) -> tuple[Counter, Counter, int]:
    tokens, finals, seen = Counter(), Counter(), set()
    for article in _articles(root):
        for sentence in SPLIT.split(article.get("News Content") or ""):
            sentence = sentence.strip()
            if len(sentence) < 20 or sentence in seen or not re.search(r"[඀-෿]", sentence):
                continue
            seen.add(sentence)
            words = [w for w in (w.strip(PUNCT) for w in sentence.split()) if w]
            tokens.update(words)
            if words:
                finals[words[-1]] += 1
    return tokens, finals, len(seen)


def build(tokens: Counter, finals: Counter, sentences: int) -> dict:
    past = {masc: [masc, fem if fem and tokens[fem] >= MIN_FORM else None, plural]
            for masc, fem, plural in IRREGULAR}
    for word, n in finals.most_common():
        if n < MIN_FINAL or word in past or word.startswith(("කල", "නොකල")):  # කල = misspelt කළ
            continue
        if word.endswith("ේය") and len(word) > 3:
            stem = word[:-2]
            fem, plural = stem + "ාය", stem + "හ"
        elif word.endswith("ීය") and len(word) > 3:
            stem = word[:-2]
            fem, plural = stem + "ුවාය", stem + "ූහ"
        else:
            continue
        if plural in ("දුන්නහ", "ගත්තහ", "ආවහ", "දුටුවහ"):  # irregular, listed above
            continue
        if tokens[plural] >= MIN_FORM:
            past[word] = [word, fem if tokens[fem] >= MIN_FORM else None, plural]
    present = [
        [word, word[:-2] + "ති"]
        for word, n in finals.most_common()
        if n >= MIN_FINAL and word.endswith("යි") and len(word) > 3 and tokens[word[:-2] + "ති"] >= MIN_FORM
    ]
    return {
        "documentation": (
            "Formal written Sinhala finite verb forms for journal_rules.py agreement checks. "
            f"Generated by scripts/build_journal_verb_forms.py from {sentences:,} unique sentences of "
            "published Sinhala news (Lankadeepa, ITN, Ada Derana). A past row is "
            "[masculine/neuter singular, feminine singular or null, plural]; a present row is "
            f"[singular, plural]. A form is kept only if it ends at least {MIN_FINAL} sentences "
            f"(the base form) or appears at least {MIN_FORM} times (the other forms). Irregular "
            "plurals (දුන්හ, ගත්හ, ආහ, කීහ, වූහ) are listed by hand and checked the same way."
        ),
        "past": sorted(past.values(), key=lambda row: -finals[row[0]]),
        "present": present,
        "colloquial_to_plural": {k: v for k, v in COLLOQUIAL_TO_PLURAL.items() if tokens[v] >= MIN_FORM},
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--research-root", type=Path, default=RESEARCH)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    data = build(*count(args.research_root))
    args.output.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"{len(data['past'])} past rows, {len(data['present'])} present rows -> {args.output}")


if __name__ == "__main__":
    main()
